def name(value):
    value = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", value)
    return value.replace(".", "_").upper()


def expressions():
    result = []
    for struct, members in STRUCTS.items():
        prefix = name(struct)
        result.append((f"WASM_SIZEOF_{prefix}", f"sizeof(struct {struct})"))
        for member in members.split():
            result.append((f"WASM_OFFSETOF_{prefix}_{name(member)}", f"offsetof(struct {struct}, {member})"))
    return result


def compiler_path():
    sdk = Path(os.environ.get("WASI_SDK_PATH", "/opt/wasi-sdk"))
    candidate = sdk / "bin" / "clang"
    return str(candidate) if candidate.exists() else (shutil.which("clang") or "clang")


def generate(clang):
    items = expressions()
    if len({key for key, _ in items}) != len(items):
        raise ValueError("duplicate generated constant name")
    source = "#include <stddef.h>\n#include <runtime.h>\n#include <libusb.h>\n#include <netinet/in.h>\n#include <sys/time.h>\n"
    source += "\n".join(f"const unsigned long long {key} = {expr};" for key, expr in items)
    command = [clang, "--target=wasm32-wasip1", "-D_WASI_EMULATED_GETPID", "-I", str(ROOT / "include"), "-I", str(ROOT / "toolchain/include"),
               "-include", str(ROOT / "toolchain/include/shim_sockets.h"), "-S", "-emit-llvm", "-x", "c", "-o", "-", "-"]
    result = subprocess.run(command, input=source, text=True, capture_output=True, check=False)
    if result.returncode:
        raise ValueError(f"wasm32 compiler failed:\n{result.stderr}")
    found = {}
    pattern = re.compile(r"^@(WASM_[A-Z0-9_]+)\s*=.*?\bconstant i64 (\d+)(?:,|\s|$)", re.MULTILINE)
    for key, value in pattern.findall(result.stdout):
        if key in found:
            raise ValueError(f"duplicate compiler output for {key}")
        found[key] = int(value)
    expected = {key for key, _ in items}
    if set(found) != expected:
        raise ValueError(f"unexpected compiler output: missing={sorted(expected - set(found))}, extra={sorted(set(found) - expected)}")
    header = NOTICE + "#ifndef PAK_WASM_LAYOUT_H\n#define PAK_WASM_LAYOUT_H\n\n"
    header += "\n".join(f"#define {key} {found[key]}" for key, _ in items)
    header += "\n\n#endif\n"
    types = NOTICE + "\n" + "\n".join(f"export declare const {key}: {found[key]};" for key, _ in items) + "\n"
    return {ROOT / "src/wasm/layout.h": header, ROOT / "typescript/types/wasm-layout.d.ts": types}


def main():
    try:
        outputs = generate(compiler_path())
        for path, content in outputs.items():
            path.write_text(content, encoding="utf-8")
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    print("Regenerated output files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
